"""Viewer entry point: python view.py --config configs/default.yaml (needs a finished run)."""
import argparse, logging, sys
from pathlib import Path

import yaml

from src import stage_io, viewer
from src.constants import Config

log = logging.getLogger("view")

def resolve_run_dir(cfg: dict, config_path: Path) -> Path:
    """<ws>/results/<id>, id = run.id or the config stem (same rule as main.py)."""

    run_id = cfg["run"]["id"] or config_path.stem
    cfg["run"]["id"] = run_id

    return stage_io.workspace(cfg) / "results" / run_id

def main():

    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="configs/default.yaml")
    args = parser.parse_args()
    config_path = Path(args.config)
    raw = yaml.safe_load(open(config_path)) or {}
    cfg = Config.model_validate(raw).model_dump()
    logging.basicConfig(level=cfg["run"]["log_level"], format="%(asctime)s %(name)s %(levelname)s %(message)s",
                        handlers=[logging.StreamHandler(sys.stdout)])
    run_dir = resolve_run_dir(cfg, config_path)
    if not run_dir.exists():
        sys.exit(f"{run_dir} does not exist; run main.py --config {config_path} first")

    log.info("viewer on %s", run_dir)
    out = viewer.run(cfg, str(run_dir))
    if out is not None:
        log.info("video: %s", out)

if __name__ == "__main__":
    main()
