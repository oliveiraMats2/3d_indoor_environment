"""Interactive viewer: python3 view.py [<config>.yaml] [--cloud NAME] (or --config <path>; needs a finished
run of the same config; main.py records the orbit video itself). NAME: sparse, mesh or any dense method
written under dense/<method>/ (patch_match, plane_sweep, casmvsnet, ...); default: first of viewer.clouds."""
import argparse, logging, os, sys
from pathlib import Path

import yaml

from src import stage_io, viewer
from src.constants import Config

log = logging.getLogger("view")

def resolve_run_dir(cfg: dict, config_path: Path) -> Path:
    """run_dir of main.py: stage_io.resolve_paths fills id, tag and the <ws>/... paths in cfg."""

    stage_io.resolve_paths(cfg, config_path)

    return stage_io.run_dirs(cfg)[0]

def main():

    pre = argparse.ArgumentParser(add_help=False)
    pre.add_argument("--cloud", help="sparse | mesh | <dense method> (default: first of viewer.clouds)")
    opts, rest = pre.parse_known_args()
    if "-h" in rest or "--help" in rest:
        print("extra option: --cloud NAME  sparse | mesh | any dense/<method> (default: first of viewer.clouds)")
    config_arg = stage_io.config_arg("Interactive Open3D viewer of a finished run of this config.", rest)
    config_path = stage_io.enter_repo(config_arg, os.path.dirname(os.path.abspath(__file__)))  # cwd = repo root
    raw = yaml.safe_load(open(config_path)) or {}
    cfg = Config.model_validate(raw).model_dump()
    logging.basicConfig(level=cfg["run"]["log_level"], format="%(asctime)s %(name)s %(levelname)s %(message)s",
                        handlers=[logging.StreamHandler(sys.stdout)])
    run_dir = resolve_run_dir(cfg, config_path)
    if not run_dir.exists():
        sys.exit(f"{run_dir} does not exist; run python3 main.py {config_path} first")

    log.info("viewer on %s (cloud=%s)", run_dir, opts.cloud or "viewer.clouds[0]")
    viewer.run(cfg, str(run_dir), interactive=True, cloud=opts.cloud)

if __name__ == "__main__":
    main()
