"""Video reading: stride sampling, reading by index and fps."""
import cv2

def fps(video):

    cap = cv2.VideoCapture(video)
    value = cap.get(cv2.CAP_PROP_FPS)
    cap.release()

    return value

def count(video):

    cap = cv2.VideoCapture(video)
    value = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    cap.release()

    return value

def sample(video, stride):
    """Yield (index, frame) for 1 of every `stride` frames."""
    frames = _frames(video)
    for i, f in frames:

        if i % stride == 0:
            yield i, f

def read(video, indices):
    """Yield (index, frame) only for the requested indices."""
    pending = set(indices)
    frames = _frames(video)
    for i, f in frames:

        if not pending:
            break

        if i in pending:
            pending.discard(i)
            yield i, f

def _frames(video):

    cap = cv2.VideoCapture(video)
    i = 0

    while True:

        ok, f = cap.read()
        if not ok:
            break

        yield i, f
        i += 1

    cap.release()
