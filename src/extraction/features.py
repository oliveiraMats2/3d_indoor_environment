"""Resize, convert to gray and detect ORB on one frame."""
import cv2
import numpy as np

def to_gray(frame, width):

    s = width / frame.shape[1]
    small = cv2.resize(frame, None, fx=s, fy=s, interpolation=cv2.INTER_AREA)
    gray = cv2.cvtColor(small, cv2.COLOR_BGR2GRAY)

    return gray

def detect(orb, gray):
    """Return (Nx2 float32 points, descriptors or None)."""
    kp, desc = orb.detectAndCompute(gray, None)
    if kp:
        coords = [k.pt for k in kp]
        pts = np.float32(coords)

    else:
        pts = np.zeros((0, 2), np.float32)

    return pts, desc
