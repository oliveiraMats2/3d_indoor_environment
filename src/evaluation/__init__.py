"""Stage 5 orchestration: metrics are produced before the final report."""
import logging
from pathlib import Path

from src.evaluation import ablation, loop_drift, metric_error, reprojection

log = logging.getLogger(__name__)

ARTIFACTS = ("evaluation.csv", "metric_error.csv", "loop_drift.csv", "ablation.csv")


def _clear_previous(run_dir: str, artifacts_dir: str) -> None:
    """Prevent a cached run from placing stale Stage 5 values in the new report."""

    for name in ARTIFACTS:
        Path(artifacts_dir, name).unlink(missing_ok=True)
    evaluation_dir = Path(run_dir, "evaluation")
    if evaluation_dir.is_dir():
        for path in evaluation_dir.glob("*.npy"):
            path.unlink()


def run(cfg: dict, run_dir: str, artifacts_dir: str) -> dict:
    """Run every Stage 5 metric and return the artifacts that were generated."""

    _clear_previous(run_dir, artifacts_dir)
    if not cfg["evaluation"]["enabled"]:
        log.info("evaluation disabled")
        return {}

    Path(run_dir, "evaluation").mkdir(parents=True, exist_ok=True)
    Path(artifacts_dir).mkdir(parents=True, exist_ok=True)
    outputs = {
        "reprojection": reprojection.run(cfg, run_dir, artifacts_dir),
        "metric_error": metric_error.run(cfg, run_dir, artifacts_dir),
        "loop_drift": loop_drift.run(cfg, run_dir, artifacts_dir),
    }
    if cfg["evaluation"].get("ablation_runs"):
        outputs["ablation"] = ablation.run(cfg, run_dir, artifacts_dir)

    generated = sum(value is not None for value in outputs.values())
    log.info("evaluation: %d/%d metric groups generated", generated, len(outputs))
    return outputs
